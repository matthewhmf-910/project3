"""Score + sound design for the reel, synthesised in code from film/timing.json.

    python3 film/audio.py dist/film

Writes <out>/audio/{music,sfx,mix,music_only}.wav (48 kHz stereo), muxes
reel_sound.mp4 and reel_music_only.mp4 next to reel.mp4, writes js/timing.js
for the picture, then measures loudness / true peak / sync and prints a report.
Every value is a function of time; the only noise source is a seeded RNG.
"""
import json
import os
import re
import subprocess
import sys

import imageio_ffmpeg
import numpy as np
from scipy.io import wavfile
from scipy.signal import butter, sosfilt

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
OUT = sys.argv[1] if len(sys.argv) > 1 else os.path.join(ROOT, "dist", "film")
FF = imageio_ffmpeg.get_ffmpeg_exe()
SR = 48000
T = json.load(open(os.path.join(ROOT, "film", "timing.json")))
DUR = T["duration"]
N = int(SR * DUR)
t = np.arange(N) / SR
rng = np.random.default_rng(2026)
BEAT = 60 / T["bpm"]
beats = [T["first_beat"] + k * BEAT for k in range(int((DUR - T["first_beat"]) / BEAT) + 1)]
H = {k: v["t"] for k, v in T["hits"].items()}

# picture reads the same numbers
with open(os.path.join(ROOT, "js", "timing.js"), "w") as fh:
    fh.write("// Generated by film/audio.py from film/timing.json - the shared clock for picture and sound.\n")
    fh.write("window.REEL_TIMING = " + json.dumps({k: v["t"] for k, v in T["hits"].items()}) + ";\n")
    fh.write("window.REEL_TIMING_DETAIL = " + json.dumps({"reform": T["hits"]["reform"].get("letters", {})}) + ";\n")


def bp(x, lo, hi, order=4):
    return sosfilt(butter(order, [lo, hi], btype="band", fs=SR, output="sos"), x)


def lp(x, f, order=4):
    return sosfilt(butter(order, f, btype="low", fs=SR, output="sos"), x)


def hp(x, f, order=4):
    return sosfilt(butter(order, f, btype="high", fs=SR, output="sos"), x)


def env(t0, a, d, length=None):
    """attack a s, exponential decay with time-constant d, from t0"""
    x = t - t0
    e = np.where(x < 0, 0, np.where(x < a, x / max(a, 1e-4), np.exp(-(x - a) / d)))
    if length:
        e *= np.clip((t0 + length - t) / 0.05, 0, 1)
    return e


def note(f, t0, length, vel=1.0, bright=1.0):
    """warm electric-piano-ish tone: sine + soft 2nd/3rd partials, gentle tremolo"""
    x = t - t0
    on = (x >= 0) & (x < length + 1.2)
    out = np.zeros(N)
    xs = x[on]
    tone = (np.sin(2 * np.pi * f * xs) + 0.35 * bright * np.sin(2 * np.pi * 2 * f * xs) * np.exp(-xs * 3)
            + 0.12 * bright * np.sin(2 * np.pi * 3 * f * xs) * np.exp(-xs * 5))
    trem = 1 + 0.06 * np.sin(2 * np.pi * 4.2 * xs)
    a = np.clip(xs / 0.012, 0, 1) * np.exp(-xs / 2.2) * np.clip((length + 1.2 - xs) / 1.2, 0, 1)
    out[on] = vel * tone * trem * a
    return out


hz = lambda m: 440 * 2 ** ((m - 69) / 12)

# ------------------------------------------------------------------ music
# D major colour, one chord per 2 beats, the drop on the strike, resolve on type_land
CH = [
    (0.0, [50, 57, 62, 66, 69, 76]),            # Dmaj9 (pad intro)
    (H["catch"], [47, 54, 62, 66, 69, 73]),     # Bm9
    (H["ring_pass"], [43, 55, 59, 62, 66, 73]), # Gmaj7#11-ish
    (H["strike"], [40, 55, 59, 62, 66, 71]),    # Em9      (drop)
    (H["splash"], [45, 55, 59, 62, 64, 69]),    # A13sus
    (H["type_land"], [50, 57, 61, 64, 66, 69]), # Dmaj9/6  (resolve, rings out)
]
music = np.zeros((N, 2))
for i, (c0, notes) in enumerate(CH):
    c1 = CH[i + 1][0] if i + 1 < len(CH) else DUR
    root, voicing = notes[0], notes[1:]
    # bass an octave up from before, with partials, so a phone speaker still hears the line
    bass = note(hz(root), c0, c1 - c0, 0.5, bright=1.0)
    for j, m in enumerate(voicing):
        strum = c0 + 0.018 * j
        v = note(hz(m), strum, c1 - c0, 0.16, bright=0.9 if c0 >= H["strike"] else 0.6)
        pan = (j / (len(voicing) - 1)) * 0.8 - 0.4
        music[:, 0] += v * (0.5 - pan / 2)
        music[:, 1] += v * (0.5 + pan / 2)
    music[:, 0] += bass * 0.5
    music[:, 1] += bass * 0.5

# soft pad under everything (filtered saw-ish), fades in from frame 0 so the hook has air
pad = sum(np.sin(2 * np.pi * hz(m) * t + k) / (k + 1) for k, m in enumerate([62, 66, 69, 74]))
pad = hp(lp(pad, 1800), 300) * np.clip(t / 0.6, 0, 1) * 0.05
music += pad[:, None]

# percussion: shaker 8ths from the catch, warm kick on beats from the drop to the resolve
noise = rng.standard_normal(N)
shaker = np.zeros(N)
for b in beats:
    for half in (0, BEAT / 2):
        tt = b + half
        if H["catch"] - 0.01 <= tt < DUR - 0.3:
            shaker += env(tt, 0.004, 0.035) * (0.55 if half else 0.35)
shaker = hp(noise * shaker, 6000) * 0.09
kick = np.zeros(N)
for b in beats:
    if H["strike"] - 0.01 <= b <= H["type_land"] + 0.01:
        x = t - b
        on = (x >= 0) & (x < 0.5)
        f = 85 + 90 * np.exp(-x[on] / 0.025)
        kick[on] += np.sin(2 * np.pi * np.cumsum(f) / SR) * np.exp(-x[on] / 0.12) * 0.35
        kick[on] += hp(noise, 2500)[on] * np.exp(-x[on] / 0.008) * 0.08  # beater click: audible on phones
music += (shaker + kick)[:, None]

# marimba line in the 500-1500 Hz band: bright, summery, carries the score on small speakers
mallet = np.zeros(N)
for i, (c0, notes) in enumerate(CH):
    c1 = CH[i + 1][0] if i + 1 < len(CH) else DUR
    if c0 < H["catch"] - 0.01:
        continue
    tones = [m + 12 for m in notes[2:]]
    k = 0
    tt = c0
    while tt < c1 - 0.05:
        f = hz(tones[(k * 2) % len(tones)])
        x = t - tt
        on = (x >= 0) & (x < 0.6)
        mallet[on] += (np.sin(2 * np.pi * f * x[on]) + 0.25 * np.sin(2 * np.pi * 3.9 * f * x[on]) * np.exp(-x[on] / 0.02)) * np.exp(-x[on] / 0.22) * (0.16 if k % 2 == 0 else 0.11)
        k += 1
        tt += BEAT / 2
music += np.stack([mallet * 0.9, mallet * 1.1], 1)

# air: closed hats on the 8ths from the drop (8 kHz+), so the score is not dull
hats = np.zeros(N)
for b in beats:
    for half in (0, BEAT / 2):
        if H["strike"] - 0.01 <= b + half < DUR - 0.2:
            hats += env(b + half, 0.001, 0.02) * (0.6 if half else 0.35)
music += (hp(noise, 8000) * hats * 0.12)[:, None]
# riser into the strike, then a real drop: pre-drop music sits ~2.5 dB lower, post-drop ~+0.8 dB
riser = hp(noise, 1500) * np.clip((t - (H["strike"] - 0.65)) / 0.65, 0, 1) ** 2 * (t < H["strike"]) * 0.18
music += riser[:, None]
music *= np.where(t < H["strike"], 0.75, 1.1)[:, None]
# ending: the resolving chord decays over the last 0.6 s to silence (no chop, no click on loop)
music *= np.clip((DUR - t) / 0.6, 0, 1)[:, None] ** 1.5
music = np.stack([hp(music[:, 0], 110), hp(music[:, 1], 110)], 1)  # no sub energy a phone cannot play

# ------------------------------------------------------------------ sound effects
# each on its own band, above the music's body
sfx = np.zeros(N)
seg = lambda t0, length: (t >= t0) & (t < t0 + length)


def whoosh(t0, length, lo, hi, gain, rise=True):
    x = np.clip((t - t0) / length, 0, 1)
    shape = np.sin(np.pi * x) ** 2 * seg(t0, length)
    f = lo + (hi - lo) * (x if rise else 1 - x)
    # moving band: crossfade three static bands by the sweep position
    bands = [bp(noise, max(80, c * 0.7), c * 1.3) for c in (lo, (lo + hi) / 2, hi)]
    w = [np.clip(1 - np.abs((f - c) / ((hi - lo) / 2 + 1)), 0, 1) for c in (lo, (lo + hi) / 2, hi)]
    return gain * shape * sum(b * wi for b, wi in zip(bands, w))


roll = whoosh(H["roll"], 0.95, 500, 1500, 0.75)                                    # roll down the chute
roll *= 1 + 0.5 * np.sin(2 * np.pi * 9 * np.clip(t - H["roll"], 0, None))           # a lemon tumbling, not just air
sfx += roll
sfx += lp(np.sin(2 * np.pi * 820 * t) * env(H["catch"], 0.001, 0.05) + 0.5 * np.sin(2 * np.pi * 1530 * t) * env(H["catch"], 0.001, 0.03), 4000) * 0.7  # wooden tock
sfx += hp(noise, 2000) * env(H["catch"], 0.0005, 0.006) * 0.25                   # tock click
sfx += whoosh(H["rings"] - 0.1, 0.35, 1200, 3200, 0.5)                            # rings turn
sfx += whoosh(H["ring_pass"] - 0.02, 0.45, 900, 2400, 0.75)                       # lemon through the rings (from the contact)
sfx += whoosh(H["lift"] - 0.05, 0.3, 1500, 4000, 0.35)                            # L lifts
sfx += hp(noise, 3500) * env(H["strike"], 0.003, 0.08) * 0.3                      # slice "shk" (low crest factor: the limiter must not eat it)
sfx += np.sin(2 * np.pi * 130 * t) * env(H["strike"], 0.002, 0.16) * 0.55          # low hit: the strike is the climax
sfx += bp(noise, 3000, 9000) * env(H["strike"], 0.003, 0.5) * 0.10                  # cymbal-like swell off the cut
sfx += np.sin(2 * np.pi * 2960 * t) * env(H["strike"], 0.001, 0.18) * 0.30        # blade ring
sfx += bp(noise, 2000, 5000) * env(H["strike"], 0.004, 0.3) * 0.9                  # bright body: the climax on a phone too
sfx += bp(noise, 150, 400) * env(H["strike"], 0.006, 0.32) * 1.5                     # chest: weight a phone can still play
sfx += np.sin(2 * np.pi * 220 * t) * env(H["strike"], 0.004, 0.2) * 0.4
# the climax as a chord stab on the drop chord (Em9 tones, all above a phone's 200 Hz roll-off).
# Sustained tones have a low crest factor, so the master's limiter keeps it the loudest moment;
# a noise burst (~12 dB crest) was being clamped ~10 dB by the limiter and lost to the whooshes.
xs = t - H["strike"]
stab_env = np.clip(xs / 0.006, 0, 1) * np.where(xs < 0.16, 1.0, np.exp(-(xs - 0.16) / 0.12)) * (xs >= 0)
stab = sum(np.sin(2 * np.pi * hz(m) * t + k) * (1 if m < 72 else 0.6) for k, m in enumerate([64, 67, 71, 74, 76, 78]))
sfx += stab * stab_env * 0.55
sfx += bp(noise, 2500, 7000) * env(H["strike"] + 0.03, 0.01, 0.06) * 0.12          # juice spritz
fall_len = H["splash"] - H["fall"]
fall = whoosh(H["fall"], fall_len, 600, 2200, 1.0, rise=False)
# builds toward the splash instead of peaking mid-air (its middle was louder than the strike)
fall *= np.clip((t - H["fall"]) / fall_len, 0, 1) ** 1.5 * 1.6
sfx += fall                                                                          # the wheel falls
for tc in sorted(set(T["hits"]["reform"].get("letters", {}).values())):             # each letter clicks home as it lands
    sfx += bp(noise, 2500, 6000) * env(tc, 0.0005, 0.012) * 0.14  # well under the strike
sp = H["splash"]
sfx += lp(noise, 2500) * env(sp, 0.002, 0.07) * 0.8                                # splash body
sfx += whoosh(5.3, 0.9, 400, 1200, 0.05)                                            # the spent lemon rolls away (quiet: not a peak)
sfx += bp(noise, 1500, 4000) * env(6.17, 0.005, 0.06) * 0.35                         # air flick as it leaves frame
for k in range(6):                                                                 # bubbles
    tb = sp + 0.04 + k * 0.045
    x = t - tb
    on = (x >= 0) & (x < 0.08)
    f = 900 + 500 * k % 700 + 2500 * x[on]
    sfx[on] += np.sin(2 * np.pi * np.cumsum(np.full(on.sum(), 1.0) * f) / SR) * np.exp(-x[on] / 0.02) * 0.08
sfx += lp(np.sin(2 * np.pi * 240 * t) * env(H["stamp"], 0.003, 0.08), 800) * 0.5   # stamp body (above phone roll-off)
sfx += bp(noise, 1200, 5000) * env(H["stamp"], 0.001, 0.035) * 0.45               # the slap of the press
sfx += hp(noise, 5000) * env(H["type_land"], 0.002, 0.25) * 0.16                  # settle shimmer
sfx *= np.clip((DUR - t) / 0.4, 0, 1)

# duck the music a touch under the biggest hits
duck = 1 - 0.5 * np.maximum.reduce([env(H[k], 0.01, 0.18) for k in ("catch", "splash", "stamp")])  # not the strike: it is the drop
MUSIC_GAIN = 0.42  # music sits low; effects ride 6-10 dB over it
music_mix = music * duck[:, None] * MUSIC_GAIN
mix = music_mix + np.stack([sfx * 0.95, sfx * 1.05], 1)

os.makedirs(os.path.join(OUT, "audio"), exist_ok=True)
def write(name, x):
    x = x / max(1e-9, np.abs(x).max()) * 0.5
    wavfile.write(os.path.join(OUT, "audio", name), SR, (x * 32767).astype(np.int16))
write("music_raw.wav", music)
write("sfx.wav", np.stack([sfx, sfx], 1))
write("mix_raw.wav", mix)


def integrated(x):
    """EBU R128 integrated loudness (LUFS) of a float signal, measured by ffmpeg."""
    tmp = os.path.join(OUT, "audio", "_measure.wav")
    wavfile.write(tmp, SR, (np.clip(x, -1, 1) * 32767).astype(np.int16))
    r = subprocess.run([FF, "-hide_banner", "-i", tmp, "-af", "ebur128", "-f", "null", "-"], capture_output=True, text=True).stderr
    os.remove(tmp)
    return float(re.findall(r"I:\s+(-?[\d.]+) LUFS", r)[-1])


def master(x, target=-14.0, ceiling_db=-2.4):  # -2.0: AAC encoding adds ~0.4 dB of true peak
    """Deterministic master: one linear gain to the target loudness, then a look-ahead
    true-peak limiter (peaks found on a 4x oversampled signal). ffmpeg's loudnorm was
    replaced because, when linear gain would break the true-peak limit, it silently
    switches to dynamic mode and compresses: it turned the strike (the climax) down
    and the quiet passages up, so the shipped mix contradicted the pre-master QA."""
    from scipy.signal import resample_poly
    x = np.atleast_2d(x.T).T if x.ndim == 1 else x
    for _ in range(3):  # gain, limit, re-measure (limiting lowers loudness slightly)
        g = 10 ** ((target - integrated(x)) / 20)
        x = x * g
        ceil = 10 ** (ceiling_db / 20)
        peak = np.max([np.abs(resample_poly(x[:, c], 4, 1)).reshape(-1, 4).max(1)[: len(x)] for c in range(x.shape[1])], 0)
        need = np.minimum(1.0, ceil / np.maximum(peak, 1e-9))
        look = int(0.005 * SR)  # 5 ms look-ahead: gain is already down when the peak arrives
        from scipy.ndimage import minimum_filter1d
        gr = minimum_filter1d(need, size=2 * look + 1)
        rel = np.exp(-1 / (0.06 * SR))  # 60 ms release
        out = np.empty_like(gr)
        cur = 1.0
        for i, v in enumerate(gr):
            cur = v if v < cur else v + (cur - v) * rel
            out[i] = cur
        x = x * out[:, None]
        if abs(integrated(x) - target) < 0.3:
            break
    return x


A = os.path.join(OUT, "audio")
for name, sig in (("mix.wav", mix), ("music_only.wav", music)):
    m = master(sig / max(1e-9, np.abs(sig).max()) * 0.5)
    wavfile.write(os.path.join(A, name), SR, (np.clip(m, -1, 1) * 32767).astype(np.int16))
for wav, mp4 in (("mix.wav", "reel_sound.mp4"), ("music_only.wav", "reel_music_only.mp4")):
    subprocess.run([FF, "-y", "-loglevel", "error", "-i", os.path.join(OUT, "reel.mp4"), "-i", os.path.join(A, wav),
                    "-map", "0:v", "-map", "1:a", "-c:v", "copy", "-c:a", "aac", "-b:a", "256k", "-shortest",
                    "-movflags", "+faststart", os.path.join(OUT, mp4)], check=True)

# ------------------------------------------------------------------ measured report
def measure(path):
    r = subprocess.run([FF, "-hide_banner", "-i", path, "-af", "ebur128=peak=true", "-f", "null", "-"], capture_output=True, text=True).stderr
    i = float(re.findall(r"I:\s+(-?[\d.]+) LUFS", r)[-1])
    tp = float(re.findall(r"Peak:\s+(-?[\d.]+) dBFS", r)[-1])
    return i, tp
fail = []
for name in ("reel_sound.mp4", "reel_music_only.mp4"):
    i, tp = measure(os.path.join(OUT, name))
    print(f"{name}: {i:.1f} LUFS integrated, true peak {tp:.1f} dBTP")
    if abs(i + 14) > 1 or tp > -1:
        fail.append(name)
# phone speakers: loudness with everything under 200 Hz removed
r = subprocess.run([FF, "-hide_banner", "-i", os.path.join(OUT, "reel_sound.mp4"), "-af", "highpass=f=200,highpass=f=200,ebur128", "-f", "null", "-"], capture_output=True, text=True).stderr
phone = float(re.findall(r"I:\s+(-?[\d.]+) LUFS", r)[-1])
print(f"phone check (HP 200 Hz): {phone:.1f} LUFS (need >= -17)")
if phone < -17:
    fail.append("phone loudness")
# effects over music, per hit (window after each onset, mixed gains)
def db(x):
    return 20 * np.log10(np.sqrt(np.mean(x ** 2)) + 1e-9)
for k in ("roll", "catch", "rings", "lift", "strike", "fall", "splash", "stamp"):
    # sustained sounds are judged over their whole length, hits over the first 100 ms
    length = {"roll": 0.95, "fall": H["splash"] - H["fall"]}.get(k, 0.1)
    a, b = int(H[k] * SR), int((H[k] + length) * SR)
    margin = db(sfx[a:b]) - db(music_mix[a:b, 0])
    need = 3 if k in ("catch", "strike", "splash", "stamp", "rings") else 0
    print(f"sfx over music {k:7s}: {margin:+.1f} dB (need >= +{need})")
    if margin < need:
        fail.append("sfx level " + k)
# sync: every sfx hit's onset lands within one frame of its timing.json time
frame = 1 / T["fps"]
e = np.abs(hp(sfx, 300))
win = int(0.004 * SR)
smooth = np.convolve(e, np.ones(win) / win, mode="same")
for k in ("catch", "strike", "splash", "stamp"):
    t0 = H[k]
    lo, hi = int((t0 - 0.1) * SR), int((t0 + 0.1) * SR)
    w = smooth[lo:hi]
    onset = (lo + int(np.argmax(w > 0.3 * w.max()))) / SR
    ok = abs(onset - t0) <= frame
    print(f"sync {k:7s}: onset {onset:.3f}s vs {t0:.3f}s ({(onset - t0) * 1000:+.0f} ms) {'ok' if ok else 'OFF'}")
    if not ok:
        fail.append("sync " + k)
shipped = os.path.join(A, "_shipped.wav")
subprocess.run([FF, "-y", "-loglevel", "error", "-i", os.path.join(OUT, "reel_sound.mp4"), "-ac", "1", "-ar", str(SR), shipped], check=True)
mix_hp = hp(wavfile.read(shipped)[1].astype(np.float64) / 32768, 200)  # measured on what ships
st = lambda a, b: db(mix_hp[int(a * SR):int(b * SR)])
strike_l, reform_l = st(H["strike"], H["strike"] + 0.4), st(H["reform"], H["reform"] + 0.4)
print(f"climax: strike {strike_l:.1f} dB vs reform {reform_l:.1f} dB (strike must be louder)")
if strike_l <= reform_l:
    fail.append("climax")
# and on a phone: the strike's 250 ms must beat every other 250 ms window in the film by >= 2 dB
w = int(0.25 * SR)
starts = np.arange(0, N - w, int(0.025 * SR))
lv = np.array([db(mix_hp[a:a + w]) for a in starts])
ts = starts / SR
in_strike = (ts >= H["strike"] - 0.05) & (ts <= H["strike"] + 0.15)
strike_max, other_max = lv[in_strike].max(), lv[~((ts > H["strike"] - 0.3) & (ts < H["strike"] + 0.35))].max()
loudest_other = ts[~((ts > H["strike"] - 0.3) & (ts < H["strike"] + 0.35))][np.argmax(lv[~((ts > H["strike"] - 0.3) & (ts < H["strike"] + 0.35))])]
print(f"climax on phone: strike {strike_max:.1f} dB vs loudest other 250 ms {other_max:.1f} dB at {loudest_other:.2f}s (need +2)")
if strike_max < other_max + 2:
    fail.append("climax on phone")
print("AUDIO RESULT:", "PASS" if not fail else "FAIL " + ", ".join(fail))
