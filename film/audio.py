"""Score + sound design for the reel, synthesised in code from film/timing.json.

    python3 film/audio.py dist/film

Writes <out>/audio/{music,sfx,mix,music_only}.wav (48 kHz stereo), muxes
reel_sound.mp4 and reel_music_only.mp4 next to reel.mp4, writes js/timing.js
for the picture, then measures loudness / true peak / sync and prints a report.
Every value is a function of time; the only noise source is a seeded RNG.
"""
import json
import os
import re
import subprocess
import sys

import imageio_ffmpeg
import numpy as np
from scipy.io import wavfile
from scipy.signal import butter, sosfilt

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
OUT = sys.argv[1] if len(sys.argv) > 1 else os.path.join(ROOT, "dist", "film")
FF = imageio_ffmpeg.get_ffmpeg_exe()
SR = 48000
T = json.load(open(os.path.join(ROOT, "film", "timing.json")))
DUR = T["duration"]
N = int(SR * DUR)
t = np.arange(N) / SR
rng = np.random.default_rng(2026)
BEAT = 60 / T["bpm"]
beats = [T["first_beat"] + k * BEAT for k in range(int((DUR - T["first_beat"]) / BEAT) + 1)]
H = {k: v["t"] for k, v in T["hits"].items()}

# picture reads the same numbers
with open(os.path.join(ROOT, "js", "timing.js"), "w") as fh:
    fh.write("// Generated by film/audio.py from film/timing.json - the shared clock for picture and sound.\n")
    fh.write("window.REEL_TIMING = " + json.dumps({k: v["t"] for k, v in T["hits"].items()}) + ";\n")


def bp(x, lo, hi, order=4):
    return sosfilt(butter(order, [lo, hi], btype="band", fs=SR, output="sos"), x)


def lp(x, f, order=4):
    return sosfilt(butter(order, f, btype="low", fs=SR, output="sos"), x)


def hp(x, f, order=4):
    return sosfilt(butter(order, f, btype="high", fs=SR, output="sos"), x)


def env(t0, a, d, length=None):
    """attack a s, exponential decay with time-constant d, from t0"""
    x = t - t0
    e = np.where(x < 0, 0, np.where(x < a, x / max(a, 1e-4), np.exp(-(x - a) / d)))
    if length:
        e *= np.clip((t0 + length - t) / 0.05, 0, 1)
    return e


def note(f, t0, length, vel=1.0, bright=1.0):
    """warm electric-piano-ish tone: sine + soft 2nd/3rd partials, gentle tremolo"""
    x = t - t0
    on = (x >= 0) & (x < length + 1.2)
    out = np.zeros(N)
    xs = x[on]
    tone = (np.sin(2 * np.pi * f * xs) + 0.35 * bright * np.sin(2 * np.pi * 2 * f * xs) * np.exp(-xs * 3)
            + 0.12 * bright * np.sin(2 * np.pi * 3 * f * xs) * np.exp(-xs * 5))
    trem = 1 + 0.06 * np.sin(2 * np.pi * 4.2 * xs)
    a = np.clip(xs / 0.012, 0, 1) * np.exp(-xs / 2.2) * np.clip((length + 1.2 - xs) / 1.2, 0, 1)
    out[on] = vel * tone * trem * a
    return out


hz = lambda m: 440 * 2 ** ((m - 69) / 12)

# ------------------------------------------------------------------ music
# D major colour, one chord per 2 beats, the drop on the strike, resolve on type_land
CH = [
    (0.0, [50, 57, 62, 66, 69, 76]),            # Dmaj9 (pad intro)
    (H["catch"], [47, 54, 62, 66, 69, 73]),     # Bm9
    (H["ring_pass"], [43, 55, 59, 62, 66, 73]), # Gmaj7#11-ish
    (H["strike"], [40, 55, 59, 62, 66, 71]),    # Em9      (drop)
    (H["splash"], [45, 55, 59, 62, 64, 69]),    # A13sus
    (H["type_land"], [50, 57, 61, 64, 66, 69]), # Dmaj9/6  (resolve, rings out)
]
music = np.zeros((N, 2))
for i, (c0, notes) in enumerate(CH):
    c1 = CH[i + 1][0] if i + 1 < len(CH) else DUR
    root, voicing = notes[0], notes[1:]
    bass = note(hz(root - 12), c0, c1 - c0, 0.55, bright=0.3) + 0.6 * np.sin(2 * np.pi * hz(root - 12) * t) * env(c0, 0.04, 1.4, c1 - c0)
    for j, m in enumerate(voicing):
        strum = c0 + 0.018 * j
        v = note(hz(m), strum, c1 - c0, 0.16, bright=0.9 if c0 >= H["strike"] else 0.6)
        pan = (j / (len(voicing) - 1)) * 0.8 - 0.4
        music[:, 0] += v * (0.5 - pan / 2)
        music[:, 1] += v * (0.5 + pan / 2)
    music[:, 0] += bass * 0.5
    music[:, 1] += bass * 0.5

# soft pad under everything (filtered saw-ish), fades in from frame 0 so the hook has air
pad = sum(np.sin(2 * np.pi * hz(m) * t + k) / (k + 1) for k, m in enumerate([62, 66, 69, 74]))
pad = lp(pad, 1800) * np.clip(t / 0.6, 0, 1) * 0.05
music += pad[:, None]

# percussion: shaker 8ths from the catch, warm kick on beats from the drop to the resolve
noise = rng.standard_normal(N)
shaker = np.zeros(N)
for b in beats:
    for half in (0, BEAT / 2):
        tt = b + half
        if H["catch"] - 0.01 <= tt < DUR - 0.3:
            shaker += env(tt, 0.004, 0.035) * (0.55 if half else 0.35)
shaker = hp(noise * shaker, 6000) * 0.09
kick = np.zeros(N)
for b in beats:
    if H["strike"] - 0.01 <= b <= H["type_land"] + 0.01:
        x = t - b
        on = (x >= 0) & (x < 0.5)
        f = 52 + 70 * np.exp(-x[on] / 0.03)
        kick[on] += np.sin(2 * np.pi * np.cumsum(f) / SR) * np.exp(-x[on] / 0.16) * 0.5
music += (shaker + kick)[:, None]

# ------------------------------------------------------------------ sound effects
# each on its own band, above the music's body
sfx = np.zeros(N)
seg = lambda t0, length: (t >= t0) & (t < t0 + length)


def whoosh(t0, length, lo, hi, gain, rise=True):
    x = np.clip((t - t0) / length, 0, 1)
    shape = np.sin(np.pi * x) ** 2 * seg(t0, length)
    f = lo + (hi - lo) * (x if rise else 1 - x)
    # moving band: crossfade three static bands by the sweep position
    bands = [bp(noise, max(80, c * 0.7), c * 1.3) for c in (lo, (lo + hi) / 2, hi)]
    w = [np.clip(1 - np.abs((f - c) / ((hi - lo) / 2 + 1)), 0, 1) for c in (lo, (lo + hi) / 2, hi)]
    return gain * shape * sum(b * wi for b, wi in zip(bands, w))


sfx += whoosh(H["roll"], 0.95, 300, 900, 0.10)                                     # roll down the chute
sfx += lp(np.sin(2 * np.pi * 820 * t) * env(H["catch"], 0.001, 0.05) + 0.5 * np.sin(2 * np.pi * 1530 * t) * env(H["catch"], 0.001, 0.03), 4000) * 0.5  # wooden tock
sfx += hp(noise, 2000) * env(H["catch"], 0.0005, 0.006) * 0.25                   # tock click
sfx += whoosh(H["rings"] - 0.1, 0.35, 1200, 3200, 0.16)                           # rings turn
sfx += whoosh(H["ring_pass"] - 0.25, 0.45, 900, 2400, 0.12)                       # lemon through the rings
sfx += whoosh(H["lift"] - 0.05, 0.3, 1500, 4000, 0.10)                            # L lifts
sfx += hp(noise, 3500) * env(H["strike"], 0.0005, 0.045) * 0.55                   # slice "shk"
sfx += np.sin(2 * np.pi * 2960 * t) * env(H["strike"], 0.001, 0.18) * 0.10        # blade ring
sfx += bp(noise, 2500, 7000) * env(H["strike"] + 0.03, 0.01, 0.06) * 0.12          # juice spritz
sfx += whoosh(H["fall"], H["splash"] - H["fall"], 600, 2200, 0.09, rise=False)    # the wheel falls
for k in range(5):                                                                 # letters click home
    tc = H["reform"] + k * 0.09
    sfx += bp(noise, 2500, 6000) * env(tc, 0.0005, 0.012) * 0.22
sp = H["splash"]
sfx += lp(noise, 2500) * env(sp, 0.002, 0.07) * 0.45                               # splash body
for k in range(6):                                                                 # bubbles
    tb = sp + 0.04 + k * 0.045
    x = t - tb
    on = (x >= 0) & (x < 0.08)
    f = 900 + 500 * k % 700 + 2500 * x[on]
    sfx[on] += np.sin(2 * np.pi * np.cumsum(np.full(on.sum(), 1.0) * f) / SR) * np.exp(-x[on] / 0.02) * 0.08
sfx += lp(np.sin(2 * np.pi * 110 * t) * env(H["stamp"], 0.003, 0.09), 400) * 0.5   # stamp thud
sfx += bp(noise, 1500, 5000) * env(H["stamp"], 0.002, 0.03) * 0.12                # paper
sfx += hp(noise, 7000) * env(H["type_land"], 0.002, 0.25) * 0.05                  # settle shimmer

# duck the music a touch under the biggest hits
duck = 1 - 0.35 * np.maximum.reduce([env(H[k], 0.01, 0.18) for k in ("strike", "splash", "stamp")])
mix = music * duck[:, None] + np.stack([sfx * 0.95, sfx * 1.05], 1)

os.makedirs(os.path.join(OUT, "audio"), exist_ok=True)
def write(name, x):
    x = x / max(1e-9, np.abs(x).max()) * 0.5
    wavfile.write(os.path.join(OUT, "audio", name), SR, (x * 32767).astype(np.int16))
write("music_raw.wav", music)
write("sfx.wav", np.stack([sfx, sfx], 1))
write("mix_raw.wav", mix)


def loudnorm(src, dst):
    """two-pass EBU R128 to -14 LUFS, true peak <= -1.5 dBTP"""
    first = subprocess.run([FF, "-hide_banner", "-i", src, "-af", "loudnorm=I=-14:TP=-1.5:LRA=11:print_format=json", "-f", "null", "-"],
                           capture_output=True, text=True).stderr
    m = json.loads(first[first.rindex("{"):first.rindex("}") + 1])
    af = (f"loudnorm=I=-14:TP=-1.5:LRA=11:measured_I={m['input_i']}:measured_TP={m['input_tp']}:"
          f"measured_LRA={m['input_lra']}:measured_thresh={m['input_thresh']}:offset={m['target_offset']}:linear=true")
    subprocess.run([FF, "-y", "-loglevel", "error", "-i", src, "-af", af, "-ar", str(SR), dst], check=True)


A = os.path.join(OUT, "audio")
loudnorm(os.path.join(A, "mix_raw.wav"), os.path.join(A, "mix.wav"))
loudnorm(os.path.join(A, "music_raw.wav"), os.path.join(A, "music_only.wav"))
for wav, mp4 in (("mix.wav", "reel_sound.mp4"), ("music_only.wav", "reel_music_only.mp4")):
    subprocess.run([FF, "-y", "-loglevel", "error", "-i", os.path.join(OUT, "reel.mp4"), "-i", os.path.join(A, wav),
                    "-map", "0:v", "-map", "1:a", "-c:v", "copy", "-c:a", "aac", "-b:a", "256k", "-shortest",
                    "-movflags", "+faststart", os.path.join(OUT, mp4)], check=True)

# ------------------------------------------------------------------ measured report
def measure(path):
    r = subprocess.run([FF, "-hide_banner", "-i", path, "-af", "ebur128=peak=true", "-f", "null", "-"], capture_output=True, text=True).stderr
    i = float(re.findall(r"I:\s+(-?[\d.]+) LUFS", r)[-1])
    tp = float(re.findall(r"Peak:\s+(-?[\d.]+) dBFS", r)[-1])
    return i, tp
fail = []
for name in ("reel_sound.mp4", "reel_music_only.mp4"):
    i, tp = measure(os.path.join(OUT, name))
    print(f"{name}: {i:.1f} LUFS integrated, true peak {tp:.1f} dBTP")
    if abs(i + 14) > 1 or tp > -1:
        fail.append(name)
# sync: every sfx hit's onset lands within one frame of its timing.json time
frame = 1 / T["fps"]
e = np.abs(hp(sfx, 300))
win = int(0.004 * SR)
smooth = np.convolve(e, np.ones(win) / win, mode="same")
for k in ("catch", "strike", "splash", "stamp"):
    t0 = H[k]
    lo, hi = int((t0 - 0.1) * SR), int((t0 + 0.1) * SR)
    w = smooth[lo:hi]
    onset = (lo + int(np.argmax(w > 0.3 * w.max()))) / SR
    ok = abs(onset - t0) <= frame
    print(f"sync {k:7s}: onset {onset:.3f}s vs {t0:.3f}s ({(onset - t0) * 1000:+.0f} ms) {'ok' if ok else 'OFF'}")
    if not ok:
        fail.append("sync " + k)
print("AUDIO RESULT:", "PASS" if not fail else "FAIL " + ", ".join(fail))
