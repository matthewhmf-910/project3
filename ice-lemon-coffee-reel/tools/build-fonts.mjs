// Builds fonts/fonts.css + fonts/files/*.woff2 from @fontsource packages,
// keeping only the subsets whose unicode-range covers a character used in index.html.
// usage: node tools/build-fonts.mjs <path-to-node_modules>
import fs from 'node:fs';
import path from 'node:path';

const root = path.resolve(path.dirname(new URL(import.meta.url).pathname), '..');
const nm = process.argv[2];
if (!nm) { console.error('usage: node tools/build-fonts.mjs <node_modules>'); process.exit(1); }

const used = new Set([...fs.readFileSync(path.join(root, 'index.html'), 'utf8')].map(c => c.codePointAt(0)));
for (let c = 0x20; c < 0x7f; c++) used.add(c);

const wanted = [
  ['anton', [400]], ['cormorant-garamond', [500]], ['work-sans', [500, 600]], ['space-mono', [400, 700]],
  ['noto-sans-tc', [700, 900]], ['noto-serif-tc', [900]],
];
const outDir = path.join(root, 'fonts', 'files');
fs.rmSync(path.join(root, 'fonts'), { recursive: true, force: true });
fs.mkdirSync(outDir, { recursive: true });

const inRange = (range) => range.split(',').some(r => {
  const m = r.trim().replace(/^U\+/i, '');
  const [a, b] = m.includes('-') ? m.split('-') : [m, m];
  const lo = parseInt(a.replace(/\?/g, '0'), 16), hi = parseInt(b.replace(/\?/g, 'F'), 16);
  for (const c of used) if (c >= lo && c <= hi) return true;
  return false;
});

let css = '/* generated by tools/build-fonts.mjs — subsets of @fontsource packages (SIL OFL 1.1) */\n';
let files = 0, bytes = 0;
for (const [pkg, weights] of wanted) {
  for (const w of weights) {
    const src = fs.readFileSync(path.join(nm, '@fontsource', pkg, `${w}.css`), 'utf8');
    for (const block of src.match(/@font-face\s*{[^}]*}/g)) {
      const range = (block.match(/unicode-range:\s*([^;]+);/) || [])[1];
      if (range && !inRange(range)) continue;
      const file = block.match(/url\(\.\/files\/([^)]+\.woff2)\)/)[1];
      fs.copyFileSync(path.join(nm, '@fontsource', pkg, 'files', file), path.join(outDir, file));
      bytes += fs.statSync(path.join(outDir, file)).size; files++;
      css += block.replace(/src:[^;]+;/, `src: url(./files/${file}) format('woff2');`).replace(/font-display:\s*swap;/, 'font-display: block;') + '\n';
    }
  }
}
fs.writeFileSync(path.join(root, 'fonts', 'fonts.css'), css);
console.log(`fonts: ${files} files, ${(bytes / 1024).toFixed(0)} KB`);
